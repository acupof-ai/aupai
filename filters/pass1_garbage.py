def main():
    inp = sys.argv[1]
    out = sys.argv[2]
    compiled = [re.compile(p) for p in PATTERNS]
    kept, dropped = 0, 0
    drop_reasons = {}
    with open(inp) as f, open(out, 'w') as fo:
        for line in f:
            d = json.loads(line)
            content = d.get('content', '')
            dropped_match = None
            for i, pat in enumerate(compiled):
                if pat.search(content):
                    dropped_match = i
                    break
            if dropped_match is not None:
                dropped += 1
                reason = PATTERNS[dropped_match][:40]
                drop_reasons[reason] = drop_reasons.get(reason, 0) + 1
            else:
                fo.write(line)
                kept += 1
    print(f'kept={kept} dropped={dropped}')
    if dropped:
        print('\nTop drop reasons:')
        for r, c in sorted(drop_reasons.items(), key=lambda x: -x[1])[:15]:
            print(f'  {c:4d}  {r}')

if __name__ == '__main__':
    main()
