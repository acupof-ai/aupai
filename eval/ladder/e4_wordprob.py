def as_fraction(value):
    """A plain decimal literal -> the exact rational it names, else None."""
    if isinstance(value, bool):
        return None
    if isinstance(value, int):
        return Fraction(value)
    if isinstance(value, float):
        if value != value or value in (float("inf"), float("-inf")):
            return None
        value = str(value)
    if not isinstance(value, str):
        return None
    text = value.strip()
    if not LITERAL_RE.match(text):
        return None
    return Fraction(Decimal(text))


def canonical_decimal(fr, max_dp=MAX_DP):
    """The exact decimal string of `fr`, or None when it has no finite expansion."""
    if not isinstance(fr, Fraction):
        raise TypeError(f"canonical_decimal wants a Fraction, got {type(fr).__name__}")
    sign = "-" if fr.numerator < 0 else ""
    num = abs(fr.numerator)
    den = fr.denominator
    twos = fives = 0
    rest = den
    while rest % 2 == 0:
        rest //= 2
        twos += 1
    while rest % 5 == 0:
        rest //= 5
        fives += 1
    if rest != 1:
        return None
    dp = max(twos, fives)
    if dp > max_dp:
        return None
    scaled = num * (10 ** dp) // den
    digits = str(scaled).rjust(dp + 1, "0")
    whole, frac = (digits[:-dp], digits[-dp:]) if dp else (digits, "")
    frac = frac.rstrip("0")
    out = f"{sign}{whole}" + (f".{frac}" if frac else "")
    with localcontext() as ctx:
        ctx.prec = 50
        quotient = Decimal(fr.numerator) / Decimal(fr.denominator)
    if Decimal(out) != quotient:
        return None
    return out


def _eval_node(node, values):
    """One check node. `{"step": i}` reads an earlier step's value; ops: + - * / lit."""
    if isinstance(node, dict) and "step" in node:
        ref = node["step"]
        if not isinstance(ref, int) or not 0 <= ref < len(values):
            raise ValueError(f"step reference {ref!r} is not an earlier step")
        return values[ref]
    if isinstance(node, (str, int, float)):
        value = as_fraction(node)
        if value is None:
            raise ValueError(f"check operand {node!r} is not a plain decimal literal")
        return value
    if not isinstance(node, dict):
        raise ValueError(f"check node {node!r} is not a literal, a step reference or an op")
    op = node.get("op")
    args = node.get("args")
    if op == "lit":
        if not isinstance(args, list) or len(args) != 1:
            raise ValueError(f"check node 'lit' takes exactly one arg, got {args!r}")
        return _eval_node(args[0], values)
    if op not in ("+", "-", "*", "/"):
        raise ValueError(f"check node has unsupported op {op!r}")
    if not isinstance(args, list) or len(args) < 2:
        raise ValueError(f"check node {op!r} needs at least two args, got {args!r}")
    vals = [_eval_node(a, values) for a in args]
    if op == "+":
        out = Fraction(0)
        for v in vals:
            out += v
        return out
    if op == "-":
        out = vals[0]
        for v in vals[1:]:
            out -= v
        return out
    if op == "*":
        out = Fraction(1)
        for v in vals:
            out *= v
        return out
    out = vals[0]
    for v in vals[1:]:
        if v == 0:
            raise ZeroDivisionError("check expression divides by zero")
        out /= v
    return out


def eval_steps(steps):
    """[Fraction] per step, evaluated in order; a later step may read an earlier one."""
    if not isinstance(steps, list) or not steps:
        raise ValueError("check must be a non-empty list of steps")
    values = []
    for index, node in enumerate(steps):
        try:
            values.append(_eval_node(node, values))
        except Exception as exc:                                    # noqa: BLE001
            raise ValueError(f"step {index}: {exc}") from exc
    return values


_ARITH_TOKEN_RE = re.compile(r"\s*(\d+(?:\.\d+)?|\.\d+|[+\-*/×÷()])")


def parse_arithmetic(text):
    """An arithmetic expression as a check node, or None when it is not one.

    Recursive descent over + - * / ( ) and decimal literals. Leaves stay literal strings,
    so the node evaluates through `_eval_node` with the module's exact Fraction
    arithmetic. None means the text is not a clean expression (an unexpected character or
    unbalanced parentheses), never a guess.
    """
    tokens, position = [], 0
    body = str(text or "")
    while position < len(body):
        match = _ARITH_TOKEN_RE.match(body, position)
        if not match:
            return None
        tokens.append(match.group(1))
        position = match.end()
    if not tokens:
        return None
    state = {"i": 0}

    def peek():
        return tokens[state["i"]] if state["i"] < len(tokens) else None

    def take():
        token = peek()
        state["i"] += 1
        return token

    def factor():
        token = peek()
        if token == "-":
            take()
            inner = factor()
            return None if inner is None else {"op": "*", "args": ["-1", inner]}
        if token == "+":
            take()
            return factor()
        if token == "(":
            take()
            inner = expr()
            if inner is None or take() != ")":
                return None
            return inner
        if token is None or not re.fullmatch(r"\d+(?:\.\d+)?|\.\d+", token):
            return None
        take()
        if as_fraction(token) is None:
            return None
        return token

    def term():
        node = factor()
        if node is None:
            return None
        while peek() in ("*", "/", "×", "÷"):
            op = take()
            right = factor()
            if right is None:
                return None
            node = {"op": "*" if op in ("*", "×") else "/", "args": [node, right]}
        return node

    def expr():
        node = term()
        if node is None:
            return None
        while peek() in ("+", "-"):
            op = take()
            right = term()
            if right is None:
                return None
            node = {"op": op, "args": [node, right]}
        return node

    out = expr()
    if out is None or state["i"] != len(tokens):
        return None
    return out


def eval_arithmetic_text(text):
    """Exact value of an arithmetic expression written as text, or None.

    This is what recomputes an equation a continuation states and a GSM8K
    `<<expr=result>>` annotation. None means the text is not a clean expression or cannot
    be evaluated (division by zero), never a guess.
    """
    node = parse_arithmetic(text)
    if node is None:
        return None
    try:
        return _eval_node(node, [])
    except Exception:                                               # noqa: BLE001
        return None


def trailing_expression(question):
    """The clean arithmetic expression that ends the question, or None.

    "What is 1+1?" ends in 1+1, so the operation is recoverable and can be recomputed
    here. The match must END the question: an operation invented from a number in the
    middle of a word problem would turn a wrong gold into a wrong accusation.
    """
    text = str(question or "").strip()
    while text and text[-1] in "?？=＝.。:：":
        text = text[:-1].rstrip()
    match = re.search(r"[(\d][0-9\s+\-*/×÷().]*\Z", text)
    if not match:
        return None
    body = match.group(0).strip()
    if not any(op in body for op in "+-*/×÷"):
        return None
    return parse_arithmetic(body)


def check_from_question(question):
    """(check node, kind) recovered from the QUESTION TEXT, or (None, None).

    A word problem almost never states its own operation, so most external rows come back
    (None, None) and are unverifiable -- reported as such, never counted as checked. Where
    the text does state one ("What is 1+1?"), it is recomputed here.
    """
    tail = trailing_expression(question)
    if tail is not None:
        return tail, "question_tail"
    return None, None


def verify_item(item):
    """Independent recomputation of one item's own gold.

    Returns {"ok", "value", "canonical", "reason", "detail", "steps"}. `reason` is "ok"
    or one of check_unevaluable / steps_mismatch / no_finite_decimal /
    answer_not_a_literal / value_mismatch / not_canonical; each maps to fail_class
    `arith_check_failed` at the item level.
    """
    check = item.get("check")
    kind = item.get("check_kind", "generated")
    if kind not in VERIFIABLE_CHECK_KINDS:
        # No operation in the check: the declared answer cannot be recomputed. That is not
        # a pass. The row is scored against its declared answer and counted in
        # `unverifiable_n`, so a file of unchecked golds cannot read as a clean check.
        stated = as_fraction(item.get("answer")
                             if isinstance(item.get("answer"), (str, int, float)) else None)
        if stated is None:
            return _bad("answer_not_a_literal",
                        f"answer {item.get('answer')!r} is not a decimal literal")
        want = canonical_decimal(stated)
        if want is None:
            return _bad("no_finite_decimal",
                        f"declared answer {item.get('answer')!r} has no finite decimal form")
        return {"ok": True, "verified": False, "state": STATE_UNVERIFIABLE, "value": stated,
                "canonical": want, "reason": "no_independent_check", "steps": None,
                "detail": f"check kind {kind!r} carries no operation; the declared answer "
                          f"{want!r} is scored but not independently recomputed"}
    try:
        values = eval_steps(check)
    except Exception as exc:                                        # noqa: BLE001
        return _bad("check_unevaluable", str(exc))
    declared_steps = item.get("steps")
    if declared_steps is not None and declared_steps != len(values):
        return _bad("steps_mismatch",
                    f"steps={declared_steps} but the check chain has {len(values)}")
    final = values[-1]
    want = canonical_decimal(final)
    if want is None:
        return _bad("no_finite_decimal",
                    f"the chain's final value {final.numerator}/{final.denominator} has no "
                    f"finite decimal expansion (<= {MAX_DP} dp)")
    answer = item.get("answer")
    got = as_fraction(answer if isinstance(answer, (str, int, float)) else None)
    if got is None:
        return _bad("answer_not_a_literal", f"answer {answer!r} is not a decimal literal")
    if got != final:
        return _bad("value_mismatch",
                    f"declared {answer!r} != the chain's final {want!r} "
                    f"(exact {final.numerator}/{final.denominator})")
    if str(answer).strip() != want:
        return _bad("not_canonical", f"declared {answer!r} is not the canonical form {want!r}")
    trail = " -> ".join(canonical_decimal(v) or f"{v.numerator}/{v.denominator}" for v in values)
    return {"ok": True, "verified": True, "state": STATE_VERIFIED, "value": final,
            "canonical": want, "reason": "ok",
            "detail": f"steps {trail} (exact {final.numerator}/{final.denominator})",
            "steps": [canonical_decimal(v) for v in values]}


def _bad(reason, detail):
    return {"ok": False, "verified": False, "state": STATE_MISMATCH, "value": None,
            "canonical": None, "reason": reason, "detail": detail, "steps": None}


def arith_gate(states, operational):
    """The gate over the three states.

    A contradicted gold always fails. An unverifiable row fails the gate for the rows this
    module generates; for rows read from another file (an external set, the GSM8K sample)
    it is reported in `unverifiable_n` instead, because this module cannot make another
    author's item recomputable.
    """
    return (states.get(STATE_MISMATCH, 0) == 0
            and (not operational or states.get(STATE_UNVERIFIABLE, 0) == 0))


