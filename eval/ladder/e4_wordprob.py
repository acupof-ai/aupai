def load_gsm8k_sample(path=GSM8K_DEFAULT, lines=GSM8K_LINES):
    """(rows, info): the fixed-line GSM8K sample in the stage's row shape.

    Line numbers are 0-based indices into the file and are returned in `info` so the seal
    can name exactly which 20 problems were used. Nothing here samples.
    """
    all_lines = pathlib.Path(path).read_text(encoding="utf-8").splitlines()
    lc.require(all_lines, f"{path} is empty")
    rows, used = [], []
    for line in lines:
        lc.require(0 <= line < len(all_lines),
                   f"{path} has {len(all_lines)} lines; the fixed sample asks for {line}")
        row = json.loads(all_lines[line])
        gold = gsm8k_gold(row.get("answer", ""))
        lc.require(gold is not None, f"{path} line {line} has no number after ####")
        rows.append({
            "id": f"gsm8k:{line:04d}",
            "kind": "gsm8k",
            "lang": "en",
            "steps": None,
            "prompt": format_continuation(row["question"]),
            "answer": gold,
            "check": [{"op": "lit", "args": [gold]}],
            "check_kind": "gsm8k_gold",
            "question": row["question"],
            "gold_cot": row.get("answer", ""),
            "gsm8k_line": line,
        })
        used.append(line)
    info = {"source": str(path), "sha256": lc.sha256_file(path), "lines": used,
            "stride": GSM8K_STRIDE, "n": len(rows), "index_base": 0,
            "answer_rule": GSM8K_ANSWER_RULE}
    return rows, info


def gsm8k_gold(answer_text):
    """The gold number: after `####` (GSM8K's own convention). Canonical string or None."""
    if "####" not in (answer_text or ""):
        return None
    tail = answer_text.split("####")[-1].replace(",", "").strip()
    numbers = NUM_RE.findall(tail)
    if not numbers:
        return None
    return canonical_decimal(as_fraction(numbers[-1]))


def verify_gsm8k_cot(answer_text):
    """(ok, detail) for a GSM8K gold's own reasoning, recomputed from its annotations.

    GSM8K writes every computation as `<<expr=result>>` and ends with `#### N`. Both are
    recomputed here with Fraction arithmetic: a stated annotation whose result is wrong,
    or a `#### N` that disagrees with the last annotation, means the gold itself does not
    hold up and the item is `arith_check_failed` -- the same rule the operational set's
    step chain gets. Annotations the evaluator cannot parse are counted, never assumed
    correct.
    """
    annotations = ANNOT_RE.findall(answer_text or "")
    parsed, mismatch, unparsed = [], [], 0
    for body in annotations:
        if "=" not in body:
            unparsed += 1
            continue
        left, right = body.rsplit("=", 1)
        value = eval_arithmetic_text(left)
        stated = as_fraction(right.replace(",", "").strip())
        if value is None or stated is None:
            unparsed += 1
            continue
        parsed.append(value)
        if value != stated:
            mismatch.append({"expr": left.strip(), "stated": right.strip(),
                             "recomputed": canonical_decimal(value)})
    gold = gsm8k_gold(answer_text)
    detail = {"gold": gold, "n_annotations": len(annotations), "n_parsed": len(parsed),
              "n_unparsed": unparsed, "verified": True, "state": STATE_VERIFIED}
    if mismatch:
        detail.update({"reason": "annotation_mismatch", "mismatch": mismatch,
                       "verified": False, "state": STATE_MISMATCH})
        return False, detail
    if gold is None:
        detail.update({"reason": "no_final_answer", "verified": False,
                       "state": STATE_MISMATCH})
        return False, detail
    if parsed and parsed[-1] != as_fraction(gold):
        # The source's own working stops before the final step (a truncated CoT is the
        # common case). No annotation contradicts the gold and none of them is wrong, so
        # this is "the source cannot confirm its last value", reported and counted, never
        # scored as a model failure. A WRONG annotation above is still a hard failure.
        detail.update({"reason": "final_step_not_annotated", "verified": False,
                       "state": STATE_UNVERIFIABLE,
                       "last_annotation": canonical_decimal(parsed[-1])})
        return True, detail
    detail["reason"] = "ok"
    return True, detail


