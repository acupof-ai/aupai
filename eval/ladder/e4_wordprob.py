_FAKE_VOCAB = {}


def _fake_ids(text):
    """A stable id per word, for controls only.

    The repeat and echo criteria are TOKEN-level (E1's rule), so a control needs ids; a
    word-index stand-in exercises the same code without a tokenizer. The table is
    module-level on purpose: a per-call table gives two different words the same id and
    manufactures a full-prompt echo that no real tokenizer would produce.
    """
    ids = []
    for token in (text or "").split():
        if token not in _FAKE_VOCAB:
            _FAKE_VOCAB[token] = len(_FAKE_VOCAB) + 1000
        ids.append(_FAKE_VOCAB[token])
    return ids


def _rec(item, text, probe=None, protocol_template=PROMPT_TEMPLATE, protocol="base",
         stop_reason="max_new"):
    return {
        "id": item["id"], "lang": item["lang"], "steps": item["steps"],
        "prompt": item["prompt"], "prompt_ids": _fake_ids(item["prompt"]),
        "gen_ids": _fake_ids(text), "text": text, "n_new": len(_fake_ids(text)),
        "max_new": 256, "stop_reason": stop_reason,
        "protocol_template": protocol_template, "protocol": protocol,
        "eos_id": 99997, "im_start_id": 99998, "im_end_id": 99999,
        "topic_probe": probe or {}, "arith": verify_item(item),
    }


def _render_node(node, values):
    """One step's expression as text, the way a worked solution writes it."""
    if isinstance(node, dict) and "step" in node:
        return canonical_decimal(values[node["step"]])
    if isinstance(node, (str, int, float)):
        return canonical_decimal(as_fraction(node))
    if node.get("op") == "lit":
        return _render_node(node["args"][0], values)
    symbol = {"+": "+", "-": "-", "*": "×", "/": "÷"}[node["op"]]
    parts = [f"( {_render_node(a, values)} )" if isinstance(a, dict) and "op" in a
             else _render_node(a, values) for a in node["args"]]
    return f" {symbol} ".join(parts)


def equation_lines(item):
    """The item's own chain written as equations, the way a solution writes them."""
    values = eval_steps(item["check"])
    return [f"{_render_node(node, values)} = {canonical_decimal(value)}"
            for node, value in zip(item["check"], values)]


def solution_text(item):
    """A correct worked solution for one item, each step written as an equation.

    Built from the item's own chain, so the positive control goes through the same
    equation parser and chain rule the model's continuation does.
    """
    return "先按步骤算：\n" + "\n".join(equation_lines(item)) + f"\n答案是 {item['answer']}。"


def run_controls(rows, cfg, gsm8k_rows=None, file_rows=None, operational=True):
    """CPU-only control suite. Every entry: {"control", "ok", "detail"}.

    Positive worlds must pass; every negative world must fail on the assertion that is its
    own, and the reason is compared rather than the bare boolean. The negative worlds are
    small hand-built generations over a generated item, so the same suite controls the
    operational set and an external set.
    """
    controls = []

    def add(name, ok, detail):
        controls.append({"control": name, "ok": bool(ok), "detail": str(detail)})

    item = _pick(random.Random(7), _zh_3step(), 1, set())
    question, check, steps, answer = item[0]
    target = {"id": "ctl_zh_3s", "lang": "zh", "steps": steps,
              "prompt": format_continuation(question), "answer": answer, "check": check}
    target_ver = verify_item(target)
    add("positive_item_recomputes", target_ver["ok"], target_ver["detail"])

    good = solution_text(target)
    verdict = judge(_rec(target, good), cfg)
    add("positive_correct_three_step_solution", verdict["passed"],
        f"fail_class={verdict['fail_class']} failed={verdict['failed']} "
        f"steps={verdict['steps']}")

    values = eval_steps(check)
    wrong_step = f"12 × 3 = 37\n37 + 8 = 45\n答案是 {answer}。"
    verdict = judge(_rec(target, wrong_step), cfg)
    add("negative_wrong_step", verdict["fail_class"] == FAIL_STEP,
        f"fail_class={verdict['fail_class']} steps={verdict['steps']}")

    inconsistent = (f"先算 {canonical_decimal(values[0])}，再算 {canonical_decimal(values[1])}。"
                    f"#### {answer}\n答案：{int(values[1]) + 1}")
    verdict = judge(_rec(target, inconsistent), cfg)
    add("negative_inconsistent_final_number", verdict["fail_class"] == FAIL_AMBIGUOUS,
        f"fail_class={verdict['fail_class']} candidates={verdict['answer_candidates']}")

    chain_disagree = f"{canonical_decimal(values[0])} + {canonical_decimal(values[1])} = " \
                     f"{canonical_decimal(values[0] + values[1])}\n答案是 {int(values[-1]) + 5}。"
    verdict = judge(_rec(target, chain_disagree), cfg)
    add("negative_chain_disagrees_with_final", verdict["fail_class"] == FAIL_STEP,
        f"fail_class={verdict['fail_class']} steps={verdict['steps']}")

    verdict = judge(_rec(target, ""), cfg)
    add("negative_empty_output", verdict["fail_class"] == FAIL_EMPTY,
        f"fail_class={verdict['fail_class']}")

    repeated = "the total is 44 dollars " * 6
    verdict = judge(_rec(target, repeated), cfg)
    add("negative_repeat_loop", verdict["fail_class"] == FAIL_REPEAT,
        f"fail_class={verdict['fail_class']} repeat={verdict['repeat']}")

    echo = judge(_rec(target, target["prompt"]), cfg)
    add("negative_echo", echo["fail_class"] == FAIL_ECHO,
        f"fail_class={echo['fail_class']} echo={echo['echo']}")

    english = judge(_rec(target, "First multiply the price by the number of books, then add "
                                "the extra fee. The answer is %s." % answer), cfg)
    add("negative_lang_drift", english["fail_class"] == FAIL_LANG,
        f"fail_class={english['fail_class']} cjk_ratio={english['lang_ratio']}")

    other = rows[0]
    mini = topic_index([target, other])
    switch = judge(_rec(target, other["prompt"], probe=mini[target["id"]]), cfg)
    add("negative_topic_switch", switch["fail_class"] == FAIL_TOPIC,
        f"other={other['id']} fail_class={switch['fail_class']} topic={switch['topic']}")

    id_switch = judge(_rec(target, f"先看 e4_zh_2s_00 这道题。答案是 {answer}。",
                           probe={"other_ids": ["e4_zh_2s_00"], "other_ngrams": set()}), cfg)
    add("negative_topic_switch_by_id", id_switch["fail_class"] == FAIL_TOPIC,
        f"fail_class={id_switch['fail_class']} topic={id_switch['topic']}")

    chatml_prompt = {"id": "ctl_chatml", "lang": "zh", "steps": 2,
                     "prompt": "<|im_start|>user\n一箱有 3 个，两箱几个？<|im_end|>\n"
                               "<|im_start|>assistant\n",
                     "answer": "6", "check": [{"op": "*", "args": ["3", "2"]}]}
    chatml = judge(_rec(chatml_prompt, "6"), cfg)
    add("negative_chatml_prefix", chatml["fail_class"] == FAIL_PROTOCOL,
        f"fail_class={chatml['fail_class']} checks={[c for c in chatml['checks'] if c['check'] == 'protocol']}")
    bad_rows = validate_rows([dict(chatml_prompt, check=[{"op": "*", "args": ["3", "2"]}],
                                   steps=2)], operational=False)[0]
    add("negative_chatml_row_refused",
        any("<|im_start|>" in e for e in bad_rows), f"{bad_rows[:1]}")

    order_last = judge(_rec(target, f"先看到 {int(answer) + 100} 这个数。\n" + good), cfg)
    add("positive_last_number_rule",
        order_last["passed"] and order_last["parsed"] == answer,
        f"gold is the last number, a decoy is first: passed={order_last['passed']} "
        f"parsed={order_last['parsed']} fail_class={order_last['fail_class']}")
    order_first = judge(_rec(target, f"{answer} 是前面算出来的数。\n"
                                      + "\n".join(equation_lines(target))
                                      + f"\n最后得到 {int(answer) + 1}。"), cfg)
    add("negative_first_number_only",
        (not order_first["passed"]) and order_first["parsed"] == str(int(answer) + 1)
        and order_first["fail_class"] == FAIL_STEP,
        f"gold is the first number only: fail_class={order_first['fail_class']} "
        f"parsed={order_first['parsed']} steps={order_first['steps']}")

    missing = judge(_rec(target, "我先看看题目再想想怎么做。"), cfg)
    add("negative_no_number", missing["fail_class"] == FAIL_NO_NUMBER,
        f"fail_class={missing['fail_class']}")

    # F0: zero equations used to pass the step check. A check that runs on nothing is a
    # check that cannot fail, so it is now its own failure class.
    no_steps_ok, no_steps_detail = step_check(f"答案是 {answer}。", answer)
    add("negative_zero_equations_fails_step_check",
        (not no_steps_ok) and no_steps_detail["klass"] == FAIL_NO_STEPS
        and no_steps_detail["n_equations"] == 0,
        f"step_check('答案是 {answer}。'): {no_steps_detail}")
    no_steps_verdict = judge(_rec(target, f"答案是 {answer}。"), cfg)
    add("negative_zero_equations_fails_item",
        no_steps_verdict["fail_class"] == FAIL_NO_STEPS
        and not no_steps_verdict["passed"]
        and no_steps_verdict["n_equations"] == 0,
        f"fail_class={no_steps_verdict['fail_class']} "
        f"n_equations={no_steps_verdict['n_equations']}")

    # F3: an equation that CANNOT be evaluated is a failed step, never a skipped one.
    uneval_ok, uneval_detail = step_check("1/0 = 84\n答案是 84。", "84")
    add("negative_unevaluable_step_fails",
        (not uneval_ok) and uneval_detail["klass"] == FAIL_STEP
        and uneval_detail["reason"] == "unevaluable_step",
        f"step_check('1/0 = 84'): {uneval_detail}")
    uneval_verdict = judge(_rec(target, f"1/0 = 84\n答案是 {answer}。"), cfg)
    add("negative_unevaluable_step_fails_item",
        uneval_verdict["fail_class"] == FAIL_STEP,
        f"fail_class={uneval_verdict['fail_class']} steps={uneval_verdict['steps']}")

    wrong_answer = judge(_rec(target, "2 × 2 = 4\n答案是 4。"), cfg)
    add("negative_wrong_answer", wrong_answer["fail_class"] == FAIL_WRONG,
        f"a correct chain that answers a different question: "
        f"fail_class={wrong_answer['fail_class']} parsed={wrong_answer['parsed']}")

    broken = dict(target, answer=str(int(answer) + 2))
    broken_verdict = judge(_rec(broken, good), cfg)
    add("negative_broken_gold", broken_verdict["fail_class"] == FAIL_ARITH,
        f"fail_class={broken_verdict['fail_class']}")

    truncated = dict(target, check=check[:-1], steps=steps)
    trunc_ver = verify_item(truncated)
    add("negative_step_count_mismatch", trunc_ver["reason"] == "steps_mismatch",
        trunc_ver["detail"])

    third = {"id": "ctl_third", "lang": "zh", "steps": 1,
             "prompt": format_continuation("1 除以 3 是多少？"), "answer": "0.3",
             "check": [{"op": "/", "args": ["1", "3"]}]}
    third_ver = verify_item(third)
    add("negative_wrong_precision", (not third_ver["ok"])
        and third_ver["reason"] == "no_finite_decimal", third_ver["detail"])

    ids = [r["id"] for r in rows]
    ok_missing, _ = lc.verify_coverage(rows[:-1], ids, label="control")
    ok_dupe, _ = lc.verify_coverage(rows + [rows[0]], ids, label="control")
    add("negative_coverage_missing_id", not ok_missing, "one item dropped -> coverage FAIL")
    add("negative_coverage_duplicate_id", not ok_dupe, "one item duplicated -> coverage FAIL")

    if operational:
        # Same number of rows, one changed answer: a count mismatch would fail for the
        # wrong reason and prove nothing about catching an edited answer.
        bad = [dict(r) for r in rows]
        bad[0] = dict(bad[0], answer="999999999")
        ok_bad, bad_detail = dataset_matches_generator(bad)
        annotated = [dict(r, kind="own", gold_state="verified") for r in rows]
        ok_annotated, annotated_detail = dataset_matches_generator(annotated)
        add("positive_in_memory_annotations_ignored", ok_annotated,
            f"a run's own `kind`/gold annotations do not read as an edit: {annotated_detail[:120]}")
        add("negative_hand_edited_answer",
            (not ok_bad) and len(bad) == len(rows) and "answer" in bad_detail
            and bad[0]["id"] in bad_detail,
            f"{len(bad)} rows (same as generated); {bad_detail[:160]}")
        if file_rows is not None and DATA_DEFAULT.exists():
            ok_file, detail = dataset_matches_generator(file_rows)
            add("positive_file_matches_generator", ok_file, f"{DATA_DEFAULT.name}: {detail}")
    if gsm8k_rows:
        golds = [r for r in gsm8k_rows if r.get("gold_cot")]
        checked = [verify_gsm8k_cot(r["gold_cot"]) for r in golds]
        contradicted = [r["id"] for r, (ok, _d) in zip(golds, checked) if not ok]
        add("positive_gsm8k_gold_recomputes", not contradicted,
            f"{sum(1 for ok, _d in checked if ok)}/{len(checked)} golds consistent; "
            f"fully verified={sum(1 for _o, d in checked if d.get('verified'))}; "
            f"unparsed={sum(d.get('n_unparsed', 0) for _o, d in checked)}; "
            f"contradicted={contradicted}")
        unverified = [r["id"] for r, (_o, d) in zip(golds, checked)
                      if not d.get("verified") and _o]
        add("positive_gsm8k_unverified_reported",
            all(verify_gsm8k_cot(r["gold_cot"])[1].get("reason") == "final_step_not_annotated"
                for r in golds if r["id"] in unverified),
            f"unannotated final step, reported not failed: {unverified}")
        bad_cot = "He sells 16 - 3 - 4 = <<16-3-4=10>>10 eggs.\n#### 10"
        bad_ver = verify_gsm8k_cot(bad_cot)
        add("negative_gsm8k_annotation_mismatch", not bad_ver[0],
            f"{bad_ver[1]}")
        bad_final = "He sells 16 - 3 - 4 = <<16-3-4=9>>9 eggs.\n#### 10"
        final_ok, final_detail = verify_gsm8k_cot(bad_final)
        add("negative_gsm8k_unannotated_final_step",
            final_detail["verified"] is False
            and final_detail["state"] == STATE_UNVERIFIABLE
            and final_detail["reason"] == "final_step_not_annotated"
            and not arith_gate({STATE_UNVERIFIABLE: 1}, True),
            f"the verified predicate must be False, and it must not count as checked: "
            f"{final_detail}")
        no_marker = "He sells 9 eggs."
        add("negative_gsm8k_missing_marker", not verify_gsm8k_cot(no_marker)[0],
            f"{verify_gsm8k_cot(no_marker)[1]}")
    return controls


def _selftest_external_set():
    """Controls for the --prompts path: the audit shape, parsed to rows and rechecked.

    The external set is where a gold can arrive with no operation behind it, so the three
    states are exercised here: a question that states its own operation is recomputed, a
    question that does not is unverifiable and is never counted as checked, and a
    recomputation that disagrees with the declared answer fails the item.
    """
    import tempfile

    controls = []

    def add(name, ok, detail):
        controls.append({"control": name, "ok": bool(ok), "detail": str(detail)})

    payload = {"prompts": [
        {"id": "ext:tail", "prompt": "What is 1+1?", "answer": 2},
        {"id": "ext:wrong", "prompt": "What is 1+1?", "answer": 9},
        {"id": "ext:open", "prompt": "一支笔 25 元，一本笔记本比一支笔贵 17 元。买 2 本要多少元？",
         "answer": 85},
        {"id": "ext:steps", "prompt": "一支笔 25 元，一本笔记本比一支笔贵 17 元。买 2 本要多少元？",
         "answer": 84,
         "check": [{"op": "+", "args": ["25", "17"]},
                   {"op": "*", "args": [{"step": 0}, "2"]}]},
        {"id": "ext:steps_wrong", "prompt": "一支笔 25 元，一本笔记本比一支笔贵 17 元。买 2 本要多少元？",
         "answer": 85,
         "check": [{"op": "+", "args": ["25", "17"]},
                   {"op": "*", "args": [{"step": 0}, "2"]}]},
    ]}
    with tempfile.TemporaryDirectory() as tmp:
        path = os.path.join(tmp, "ext.json")
        with open(path, "w", encoding="utf-8") as handle:
            json.dump(payload, handle, ensure_ascii=False)
        rows, info = load_prompt_set(path, "continuation")
        # DEFINED HERE, not inherited: the five verify_item calls below read by_id, and
        # without this line the whole external-set control path died with NameError --
        # a control that never runs is a control that never fails (ruff F821, 2026-10-09).
        by_id = {r["id"]: r for r in rows}
        add("external_check_kinds",
            {r["id"]: r["check_kind"] for r in rows} == {
                "ext:tail": "question_tail", "ext:wrong": "question_tail",
                "ext:open": "literal", "ext:steps": "file_steps",
                "ext:steps_wrong": "file_steps"},
            f"check_kind {info['check_kind']}")
        tail = verify_item(by_id["ext:tail"])
        add("external_question_tail_verified",
            tail["state"] == STATE_VERIFIED and tail["canonical"] == "2",
            f"1+1 with answer 2: {tail['detail']}")
        wrong = verify_item(by_id["ext:wrong"])
        add("external_gold_mismatch_fails",
            wrong["state"] == STATE_MISMATCH and not wrong["ok"],
            f"1+1 declared as 9: {wrong['reason']} / {wrong['detail']}")
        steps_wrong = verify_item(by_id["ext:steps_wrong"])
        add("external_file_steps_mismatch_fails",
            steps_wrong["state"] == STATE_MISMATCH and not steps_wrong["ok"],
            f"25+17 then x2 declared as 85: {steps_wrong['reason']} / {steps_wrong['detail']}")
        steps_ok = verify_item(by_id["ext:steps"])
        add("external_file_steps_verified",
            steps_ok["state"] == STATE_VERIFIED and steps_ok["canonical"] == "84",
            f"{steps_ok['detail']}")
        openv = verify_item(by_id["ext:open"])
        add("external_unverifiable_is_not_a_pass",
            openv["state"] == STATE_UNVERIFIABLE and openv["ok"] and not openv["verified"],
            f"no operation in a word problem: {openv['reason']}")
        add("external_unverifiable_counted_not_gated",
            arith_gate({STATE_VERIFIED: 2, STATE_UNVERIFIABLE: 1}, False)
            and not arith_gate({STATE_VERIFIED: 2, STATE_UNVERIFIABLE: 1}, True)
            and not arith_gate({STATE_MISMATCH: 1}, False),
            "an external unverifiable row is reported; a generated one and any mismatch "
            "fail the gate")
    return controls


def control_selftest():
    """CPU-only positive/negative controls for `eval_ladder.py selftest --only e4`."""
    failures = []
    cfg = {"echo_max_overlap": 1.0, "repeat_ngram": 8, "repeat_ngram_max": 3,
           "repeat_span_ratio": 0.5, "lang_cjk": 0.3}
    try:
        rows = generate_items()
    except Exception as exc:                                        # noqa: BLE001
        print(f"FAIL e4 control: generate_items raised {exc!r}", file=sys.stderr)
        return lc.EXIT_GATE
    errors, stats = validate_rows(rows)
    if errors:
        failures.extend(f"generated dataset invalid: {e}" for e in errors)
    for lang in LANGS:
        for steps in STEP_COUNTS:
            if stats["composition"].get(f"{lang}/{steps}s", 0) < PER_GROUP:
                failures.append(f"composition {lang}/{steps} below {PER_GROUP}")
    if stats["n_distinct_answers"] != stats["n"]:
        failures.append(f"{stats['n'] - stats['n_distinct_answers']} duplicate answers")
    gsm8k_rows = None
    if GSM8K_DEFAULT.exists():
        try:
            gsm8k_rows, _info = load_gsm8k_sample()
        except Exception as exc:                                    # noqa: BLE001
            failures.append(f"GSM8K sample failed to load: {exc!r}")
    else:
        print(f"SKIP e4 GSM8K controls: {GSM8K_DEFAULT} not present", file=sys.stderr)
    controls = run_controls(rows, cfg, gsm8k_rows=gsm8k_rows, file_rows=rows)
    controls += _selftest_external_set()
    for ctl in controls:
        if not ctl["ok"]:
            failures.append(f"control {ctl['control']} failed: {ctl['detail']}")
    if failures:
        for fail in failures:
            print(f"FAIL e4 control: {fail}", file=sys.stderr)
        return lc.EXIT_GATE
    n_gsm8k = len(gsm8k_rows or [])
    print(f"PASS e4 controls: {len(rows)} generated items "
          f"({json.dumps(stats['composition'], sort_keys=True)}), "
          f"{n_gsm8k} GSM8K lines {list(GSM8K_LINES)[:3]}...+{GSM8K_LINES[-1]}, "
          f"{len(controls)} control worlds, every negative world FAILs on its own assertion")
    return lc.EXIT_OK


