def contains_run(hay, needle):
    """True when `needle` occurs as a contiguous block inside `hay`."""
    n, m = len(hay), len(needle)
    if m == 0 or m > n:
        return False
    return any(hay[i] == needle[0] and hay[i:i + m] == needle for i in range(n - m + 1))


def longest_common_run(a, b):
    """Length of the longest contiguous run of equal token ids shared by a and b."""
    if not a or not b:
        return 0
    prev = [0] * (len(b) + 1)
    best = 0
    for x in a:
        cur = [0] * (len(b) + 1)
        for j, y in enumerate(b, 1):
            if x == y:
                cur[j] = prev[j - 1] + 1
                if cur[j] > best:
                    best = cur[j]
        prev = cur
    return best


def tail_loop(ids, max_period=64, min_reps=3, min_span=24):
    """The trailing exact repetition of a period-p block, or None (E1's rule)."""
    n = len(ids)
    for period in range(1, max_period + 1):
        if period * min_reps > n:
            break
        reps = 1
        block = ids[n - period:]
        while (reps + 1) * period <= n and ids[n - (reps + 1) * period:n - reps * period] == block:
            reps += 1
        if reps >= min_reps and period * reps >= min_span:
            return {"period": period, "reps": reps, "span": period * reps}
    return None


def longest_repeat_span(ids, min_span=4):
    """The longest token span that occurs at least twice, and its share of the output.

    The search runs from the longest possible span down and stops at the first hit, so the
    reported number is the true longest repeat. Ids are packed as fixed-width bytes so a
    window is a dict key rather than a rebuilt tuple; at the 256-token cap this costs a
    few milliseconds per item.
    """
    n = len(ids)
    if n < 2 * min_span:
        return {"span": 0, "ratio": 0.0, "start": None}
    blob = b"".join(int(t).to_bytes(4, "big", signed=False) for t in ids)
    for span in range(n - 1, min_span - 1, -1):
        width = span * 4
        seen = {}
        for start in range(0, n - span + 1):
            window = blob[start * 4:start * 4 + width]
            if window in seen:
                return {"span": span, "ratio": round(span / n, 4), "start": seen[window]}
            seen[window] = start
    return {"span": 0, "ratio": 0.0, "start": None}


def repeat_stats(ids, ngram_n=8):
    """Token-level repetition evidence. Token ids, never the decoded string."""
    grams = Counter(tuple(ids[i:i + ngram_n]) for i in range(len(ids) - ngram_n + 1))
    top_gram, top_count = (None, 0)
    if grams:
        top_gram, top_count = grams.most_common(1)[0]
    span = longest_repeat_span(ids)
    return {"ngram_n": ngram_n, "max_ngram_count": top_count,
            "max_ngram": list(top_gram) if top_gram else None,
            "loop": tail_loop(ids), "longest_span": span["span"],
            "longest_span_ratio": span["ratio"]}


LATIN_RE = re.compile(r"[A-Za-z]")


def lang_stats(text, window=200):
    """(ratio, raw, detail): how much of the continuation's LANGUAGE is Chinese.

    `ratio` is the gate: CJK characters over CJK plus Latin letters, so the digits and
    operators that fill a worked arithmetic solution do not dilute the signal (the
    auditor's E1 rule divides by ALL characters, which is right for prose and wrong here);
    the 0.3 threshold is unchanged. `raw` is that auditor rule, kept per item as evidence
    so the two readings can be compared, and a continuation with no letters at all is
    reported as unjudged rather than failed.
    """
    body = (text or "")[:window]
    cjk = len(CJK_RE.findall(body))
    latin = len(LATIN_RE.findall(body))
    letters = cjk + latin
    ratio = round(cjk / letters, 4) if letters else None
    raw = round(cjk / len(body), 4) if body else 0.0
    return ratio, raw, {"cjk": cjk, "latin": latin, "chars": len(body),
                        "letters": letters, "ratio_chars": raw}


def echo_stats(prompt, prompt_ids, gen_ids, text):
    """E1's echo evidence: the token run shared with the prompt, and the literal hit."""
    run = longest_common_run(gen_ids, prompt_ids)
    ratio = round(run / len(prompt_ids), 4) if prompt_ids else 0.0
    norm_prompt = " ".join(prompt.split())
    norm_gen = " ".join((text or "").split())
    text_hit = len(norm_prompt) >= 16 and norm_prompt in norm_gen
    return {"prompt_tokens": len(prompt_ids), "longest_run": run, "ratio": ratio,
            "full_run": contains_run(gen_ids, prompt_ids), "text_contains": text_hit}


def answer_candidates(text, cues=ANSWER_CUES):
    """The numbers the continuation presents as THE answer, in order.

    After an explicit cue (`####`, 答案是, answer is, ...) inside a short window, plus the
    last number of the output, which is the value the declared answer rule reads. Two
    different values in this list is `answer_ambiguous`.
    """
    found = []
    body = text or ""
    lower = body.lower()
    for cue in cues:
        key = cue.lower()
        start = 0
        while True:
            index = lower.find(key, start)
            if index < 0:
                break
            window = body[index + len(cue):index + len(cue) + 24]
            numbers = NUM_RE.findall(window)
            if numbers:
                found.append(numbers[0])
            start = index + len(key)
    tail = NUM_RE.findall(body)
    if tail:
        found.append(tail[-1])
    return found


def token_ngrams(text, lang, n):
    """The n-grams of a question: character n-grams for zh, word n-grams for en."""
    if lang == "zh":
        tokens = list(re.sub(r"\s+", "", text or ""))
    else:
        tokens = WORD_RE.findall((text or "").lower())
    return {tuple(tokens[i:i + n]) for i in range(len(tokens) - n + 1)}


TOPIC_N = {"zh": 10, "en": 6}
#: A question shorter than the default n yields no n-gram at all, and a criterion with no
#: evidence cannot fire: "计算：7 + 6 = ?" produced none. The floor keeps short questions
#: visible; boilerplate shared by two questions is still filtered out by distinctiveness.
TOPIC_N_MIN = {"zh": 4, "en": 3}


def topic_ngram_n(text, lang):
    """The n-gram size for one question: the default, lowered for a short question."""
    tokens = (list(re.sub(r"\s+", "", text or "")) if lang == "zh"
              else WORD_RE.findall((text or "").lower()))
    return max(TOPIC_N_MIN[lang], min(TOPIC_N[lang], len(tokens) // 2))


def topic_index(rows):
    """{id: (other ids, distinctive n-grams of the other questions)}.

    An n-gram is distinctive when it occurs in exactly one question of the set, so the
    boilerplate every item of a template shares ("How many crates does the farm fill?")
    cannot fire the criterion -- only a fragment that identifies another problem does.
    """
    gram_rows = {}
    for row in rows:
        question = row.get("question") or continuation_question(row.get("prompt"))
        lang = row.get("lang") if row.get("lang") in LANGS else "zh"
        gram_rows[row["id"]] = (lang,
                                token_ngrams(question, lang, topic_ngram_n(question, lang)))
    counts = Counter()
    for _lang, grams in gram_rows.values():
        counts.update(grams)
    index = {}
    for row in rows:
        own = gram_rows[row["id"]][1]
        others, other_ids = set(), []
        for other in rows:
            if other["id"] == row["id"]:
                continue
            other_ids.append(other["id"])
            others |= {g for g in gram_rows[other["id"]][1]
                       if counts[g] == 1 and g not in own}
        index[row["id"]] = {"other_ids": other_ids, "other_ngrams": others,
                            "n_own_grams": len(own)}
    return index


def continuation_question(prompt):
    ok, question, _why = continuation_of(prompt)
    return question if ok else (prompt or "")


def topic_switch(text, probe):
    """(ok, detail): the continuation stays on this item's question."""
    if not probe:
        return True, {"reason": "no probe"}
    for other_id in probe.get("other_ids", []):
        if other_id and other_id in (text or ""):
            return False, {"reason": "other_id_in_output", "other_id": other_id}
    body = {("zh", n): token_ngrams(text, "zh", n)
            for n in range(TOPIC_N_MIN["zh"], TOPIC_N["zh"] + 1)}
    body.update({("en", n): token_ngrams(text, "en", n)
                 for n in range(TOPIC_N_MIN["en"], TOPIC_N["en"] + 1)})
    for gram in probe.get("other_ngrams", set()):
        if any(gram in grams for grams in body.values()):
            return False, {"reason": "other_question_fragment",
                           "fragment": "".join(gram) if isinstance(gram[0], str) else list(gram)}
    return True, {"reason": "ok"}


def parse_equations(text):
    """One entry per equation the continuation states.

    `ok` is True (the stated result is right), False (the stated result is wrong), or None
    (the left side is well-formed arithmetic that CANNOT be evaluated, such as a division
    by zero -- the claim is not checkable and is never skipped). A left side that is not a
    clean expression at all (unbalanced parentheses, a trailing operator) is not an
    equation claim: it is skipped, so a numbered list marker cannot fail an item.
    """
    out = []
    for match in EQ_RE.finditer(text or ""):
        left, right = match.group(1).strip(), match.group(2)
        if not any(op in left for op in "+-*/×÷"):
            continue
        if left.count("(") != left.count(")"):
            continue
        stated = as_fraction(right)
        if stated is None:
            continue
        node = parse_arithmetic(left)
        if node is None:
            continue
        try:
            value = _eval_node(node, [])
        except Exception:                                           # noqa: BLE001
            value = None
        out.append({"expr": left, "stated": right, "value": value,
                    "ok": None if value is None else value == stated,
                    "recomputed": None if value is None else canonical_decimal(value)})
    return out


def step_check(text, final_number):
    """(ok, detail): the arithmetic the continuation performs, recomputed exactly.

    Three ways to fail, and each is a failure rather than a skip. No equation at all is
    `no_steps`: a step check that runs on nothing is a check that cannot fail. A stated
    equation whose result is wrong, or that cannot be evaluated, is `step_check_failed`.
    A chain whose last value disagrees with the number the continuation presents last is
    `step_check_failed` too.
    """
    equations = parse_equations(text)
    if not equations:
        return False, {"reason": "no_equations", "klass": FAIL_NO_STEPS, "n_equations": 0,
                       "detail": "the continuation states no equation, so no step can be "
                                 "verified"}
    bad = [{"expr": e["expr"], "stated": e["stated"], "recomputed": e["recomputed"]}
           for e in equations if e["ok"] is not True]
    if bad:
        unevaluable = [b for b in bad if b["recomputed"] is None]
        return False, {"reason": "unevaluable_step"
                       if len(unevaluable) == len(bad) else "bad_step",
                       "klass": FAIL_STEP, "bad_steps": bad[:5],
                       "n_equations": len(equations)}
    chain = equations[-1]["value"]
    got = as_fraction(final_number) if final_number is not None else None
    if got is not None and got != chain:
        return False, {"reason": "final_answer_inconsistent", "klass": FAIL_STEP,
                       "chain_last": canonical_decimal(chain), "final_number": final_number,
                       "n_equations": len(equations)}
    return True, {"reason": "ok", "klass": None, "n_equations": len(equations)}


def judge(rec, cfg):
    """The stage's verdict on one generation. Pure: no torch, no filesystem.

    rec: id, lang, steps, set, prompt, prompt_ids, gen_ids, text, n_new, max_new,
    stop_reason, protocol_template, protocol, eos_id, im_start_id, im_end_id, topic_probe,
    arith (the item's own recomputation). cfg: echo_max_overlap, repeat_ngram,
    repeat_ngram_max, repeat_span_ratio, lang_cjk.
    """
    checks = []

    def add(name, ok, detail):
        checks.append({"check": name, "ok": bool(ok), "detail": detail})

    proto_ok, proto_why = protocol_ok(rec.get("prompt"), rec.get("protocol_template"),
                                      rec.get("protocol", "base"))
    special = {k: rec.get(k) for k in ("eos_id", "im_start_id", "im_end_id")
               if rec.get(k) is not None and rec[k] in list(rec.get("prompt_ids") or [])}
    add("protocol", proto_ok and not special, f"{proto_why} special_ids_in_prompt={special}")

    arith = rec.get("arith") or {}
    add("arith_check", bool(arith.get("ok")), str(arith.get("detail")))

    text = rec.get("text") or ""
    gen_ids = list(rec.get("gen_ids") or [])
    add("nonempty", rec.get("n_new", 0) > 0 and bool(text.strip()),
        f"n_new={rec.get('n_new')} chars={len(text.strip())}")

    echo = echo_stats(rec.get("prompt") or "", list(rec.get("prompt_ids") or []), gen_ids, text)
    add("no_echo", not (echo["ratio"] >= cfg["echo_max_overlap"] or echo["text_contains"]),
        json.dumps(echo, sort_keys=True))

    rep = repeat_stats(gen_ids, cfg["repeat_ngram"])
    add("no_repeat", rep["loop"] is None
        and rep["max_ngram_count"] < cfg["repeat_ngram_max"]
        and rep["longest_span_ratio"] <= cfg["repeat_span_ratio"],
        json.dumps(rep, sort_keys=True))

    ratio, raw_ratio, lang_detail = lang_stats(text)
    lang = rec.get("lang")
    if ratio is None:
        lang_ok = True
        lang_detail["reason"] = "no letters to judge; not a language failure"
    else:
        lang_ok = ratio >= cfg["lang_cjk"] if lang == "zh" else ratio <= cfg["lang_cjk"]
    add("lang", lang_ok,
        f"lang={lang} letter_ratio={ratio} threshold={cfg['lang_cjk']} "
        f"raw_cjk_ratio={raw_ratio} {json.dumps(lang_detail, sort_keys=True)}")

    switch_ok, switch_detail = topic_switch(text, rec.get("topic_probe") or {})
    add("topic", switch_ok, json.dumps(switch_detail, ensure_ascii=False, sort_keys=True))

    numbers = NUM_RE.findall(text)
    parsed = numbers[-1] if numbers else None
    candidates = answer_candidates(text)
    distinct = sorted({str(as_fraction(c)) for c in candidates if as_fraction(c) is not None})
    add("unambiguous", len(distinct) <= 1,
        f"candidates={candidates} distinct={distinct}")

    steps_ok, steps_detail = step_check(text, parsed)
    add("step_check", steps_ok, json.dumps(steps_detail, ensure_ascii=False, sort_keys=True))

    gold = arith.get("value")
    answer_ok = parsed is not None and gold is not None and as_fraction(parsed) == gold
    add("answered", answer_ok, f"parsed={parsed} gold={arith.get('canonical')}")

    order = [("protocol", FAIL_PROTOCOL), ("arith_check", FAIL_ARITH),
             ("nonempty", FAIL_EMPTY), ("no_echo", FAIL_ECHO), ("no_repeat", FAIL_REPEAT),
             ("lang", FAIL_LANG), ("topic", FAIL_TOPIC), ("unambiguous", FAIL_AMBIGUOUS)]
    by_name = {c["check"]: c for c in checks}
    failed = [c["check"] for c in checks if not c["ok"]]
    fail_class = None
    for name, klass in order:
        if not by_name[name]["ok"]:
            fail_class = klass
            break
    if fail_class is None:
        # After the format criteria, the most precise reason wins: nothing to read is
        # `no_number`; a stated step that is wrong or missing is the step class; only then
        # is a disagreement with the gold a plain wrong answer.
        if parsed is None:
            fail_class = FAIL_NO_NUMBER
        elif not steps_ok:
            fail_class = steps_detail.get("klass") or FAIL_STEP
        elif not answer_ok:
            fail_class = FAIL_WRONG
    return {
        "id": rec.get("id"),
        "passed": fail_class is None,
        "checks": checks,
        "failed": failed,
        "fail_class": fail_class,
        "stop_reason": rec.get("stop_reason"),
        "n_new": rec.get("n_new"),
        "parsed": parsed,
        "n_equations": steps_detail.get("n_equations"),
        "gold": arith.get("canonical"),
        "gold_state": arith.get("state"),
        "answer_correct": bool(answer_ok),
        "answer_candidates": candidates,
        "echo": echo,
        "repeat": rep,
        "lang_ratio": ratio,
        "lang_raw_ratio": raw_ratio,
        "lang_detail": lang_detail,
        "steps": steps_detail,
        "topic": switch_detail,
    }


