def load_prompt_set(path, template="continuation"):
    """(rows, info) for an external prompt set, in the stage's row shape.

    Shape accepted: a top level list, or an object holding one of SET_KEYS, with per entry
    an id, a question (`prompt`/`text`/`question`) and an answer. The answer is normalized
    to its exact canonical spelling and the file's own spelling is kept as `answer_raw`.
    An entry that carries its own `steps`/`check` keeps them (validated by the same
    recomputation); otherwise `check` is the single `lit` step over the answer, and the
    weaker basis is recorded per row.
    """
    source = pathlib.Path(path)
    obj = json.loads(source.read_text(encoding="utf-8"))
    if isinstance(obj, list):
        entries = obj
    else:
        entries = next((obj[k] for k in SET_KEYS if isinstance(obj.get(k), list)), None)
    lc.require(isinstance(entries, list) and entries,
               f"{path}: no prompt list found (looked for a top level list or {SET_KEYS})")
    rows, check_kinds, synthesized, used_templates = [], Counter(), 0, Counter()
    for index, entry in enumerate(entries):
        lc.require(isinstance(entry, dict), f"{path}: entry {index} is not a JSON object")
        rid = str(entry.get("id", f"ext:{index:03d}"))
        if entry.get("id") is None:
            synthesized += 1
        question = next((entry[k] for k in QUESTION_KEYS
                         if isinstance(entry.get(k), str) and entry[k].strip()), None)
        lc.require(question is not None,
                   f"{path}: entry {rid} has none of the question fields {QUESTION_KEYS}")
        question = question.strip()
        raw_answer = entry.get("answer")
        lc.require(raw_answer is not None, f"{path}: entry {rid} has no answer")
        value = as_fraction(raw_answer)
        lc.require(value is not None,
                   f"{path}: entry {rid} answer {raw_answer!r} is not a plain decimal number")
        answer = canonical_decimal(value)
        lc.require(answer is not None,
                   f"{path}: entry {rid} answer {raw_answer!r} has no finite decimal form")
        check = entry.get("check") or entry.get("steps_expr")
        if isinstance(check, list) and check:
            row_check_kind = "file_steps"
        else:
            node, node_kind = check_from_question(question)
            if node is None:
                check = [{"op": "lit", "args": [answer]}]
                row_check_kind = "literal"
            else:
                check = [node]
                row_check_kind = node_kind
        check_kinds[row_check_kind] += 1
        declared = entry.get("steps")
        steps = declared if declared in STEP_COUNTS else len(check)
        lang = entry.get("lang") if entry.get("lang") in LANGS else None
        if lang is None:
            lang = "zh" if CJK_RE.search(question) else "en"
            check_kinds["lang_inferred"] += 1
        use = template
        if template == "auto":
            pre = entry.get("prompt")
            use = "verbatim" if (isinstance(pre, str) and continuation_of(pre)[0]) else "continuation"
        if use == "verbatim":
            prompt = question
        else:
            prompt = format_continuation(question)
        used_templates[use] += 1
        rows.append({"id": rid, "kind": "external", "lang": lang, "steps": steps,
                     "prompt": prompt, "answer": answer, "check": check,
                     "answer_raw": raw_answer, "check_kind": row_check_kind,
                     "expected_template": use, "question": question})
    info = {"source": str(source), "sha256": lc.sha256_file(source), "n": len(rows),
            "set_keys": [k for k in SET_KEYS
                         if isinstance(obj, dict) and isinstance(obj.get(k), list)]
            if isinstance(obj, dict) else ["<top level list>"],
            "prompt_template": dict(used_templates), "check_kind": dict(check_kinds),
            "synthesized_ids": synthesized}
    return rows, info


