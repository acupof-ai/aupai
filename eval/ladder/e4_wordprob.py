def _pick(rng, candidates, n, seen):
    pool = list(candidates)
    rng.shuffle(pool)
    out = []
    for question, check, steps in pool:
        values = eval_steps(check)
        answer = canonical_decimal(values[-1])
        if len(values) != steps or answer is None or answer in seen:
            continue
        seen.add(answer)
        out.append((question, check, steps, answer))
        if len(out) == n:
            break
    return out


def generate_items(per_group=PER_GROUP, seed=GEN_SEED):
    """The operational set. Same seed, same rows, byte for byte.

    Every answer comes out of the step chain; nothing is typed. Answers are unique across
    the file, so one fixed number cannot score twice, and each group -- language x step
    count -- has its own items.
    """
    rng = random.Random(seed)
    seen = set()
    rows = []
    for lang in LANGS:
        for steps in STEP_COUNTS:
            picked = _pick(rng, CANDIDATE_BUILDERS[(lang, steps)](), per_group, seen)
            if len(picked) < per_group:
                raise RuntimeError(f"{lang}/{steps}-step: only {len(picked)} usable candidates")
            for index, (question, check, step_count, answer) in enumerate(picked):
                rows.append({
                    "id": f"e4_{lang}_{steps}s_{index:02d}",
                    "lang": lang,
                    "steps": step_count,
                    "prompt": format_continuation(question),
                    "answer": answer,
                    "check": check,
                })
    return rows


def render_rows(rows):
    return "".join(json.dumps({k: row[k] for k in ROW_KEYS}, ensure_ascii=False) + "\n"
                   for row in rows)


def emit_data(path, log=sys.stdout):
    """Write the committed operational set from generate_items(). Exit 3 if it is invalid."""
    rows = generate_items()
    errors, stats = validate_rows(rows)
    if errors:
        for err in errors:
            log.write(f"FAIL generated dataset: {err}\n")
        return lc.EXIT_GATE
    body = render_rows(rows)
    target = pathlib.Path(path)
    target.parent.mkdir(parents=True, exist_ok=True)
    old = target.read_text(encoding="utf-8") if target.exists() else None
    target.write_text(body, encoding="utf-8")
    state = "unchanged" if old == body else ("rewritten" if old is not None else "written")
    log.write(f"{state} {target} n={len(rows)} sha256={hashlib.sha256(body.encode()).hexdigest()}\n")
    log.write(f"composition={json.dumps(stats['composition'], sort_keys=True)}\n")
    return lc.EXIT_OK


def validate_rows(rows, operational=True, template=PROMPT_TEMPLATE):
    """(errors, stats) for the row contract -- structure and provenance, not arithmetic.

    Whether an item's own step chain holds up is NOT here: that is a per-item result with
    fail_class `arith_check_failed`, which the contract requires to be a gate failure
    rather than a refusal.
    """
    errors, composition, answers, ids = [], {}, {}, []
    for index, row in enumerate(rows):
        tag = f"row {index}"
        if not isinstance(row, dict):
            errors.append(f"{tag}: not a JSON object")
            continue
        required = ROW_KEYS if operational else ("id", "lang", "steps", "answer", "check")
        missing = [k for k in required if k not in row]
        if missing:
            errors.append(f"{tag}: missing keys {missing}")
            continue
        if "prompt" not in row:
            errors.append(f"{tag}: missing keys ['prompt']")
            continue
        tag = f"row {index} ({row['id']})"
        if row["id"] in ids:
            errors.append(f"{tag}: duplicate id")
        ids.append(row["id"])
        lang = row["lang"]
        if lang not in LANGS:
            errors.append(f"{tag}: lang {lang!r} not in {LANGS}")
        steps = row["steps"]
        if operational:
            if steps not in STEP_COUNTS:
                errors.append(f"{tag}: steps {steps!r} not in {STEP_COUNTS}")
            elif lang in LANGS:
                key = f"{lang}/{steps}s"
                composition[key] = composition.get(key, 0) + 1
            answer = row["answer"]
            if not isinstance(answer, str):
                errors.append(f"{tag}: answer {answer!r} is not a string")
            elif answer in answers:
                errors.append(f"{tag}: answer {answer!r} already used by {answers[answer]}")
            else:
                answers[answer] = row["id"]
            if not isinstance(row["check"], list):
                errors.append(f"{tag}: check must be a list of steps")
            elif len(row["check"]) != steps:
                errors.append(f"{tag}: check has {len(row['check'])} steps, declared {steps}")
        row_template = row.get("expected_template") or template
        ok, detail = protocol_ok(row["prompt"], row_template)
        if not ok:
            errors.append(f"{tag}: {detail}")
    if operational:
        for lang in LANGS:
            for steps in STEP_COUNTS:
                got = composition.get(f"{lang}/{steps}s", 0)
                if got < PER_GROUP:
                    errors.append(f"{lang}/{steps}-step: {got} items, need >= {PER_GROUP}")
    stats = {"n": len(rows), "composition": composition,
             "n_distinct_answers": len({r.get("answer") for r in rows if isinstance(r, dict)})}
    return errors, stats


def dataset_matches_generator(rows):
    """(ok, detail): the rows on disk are what generate_items() produces now.

    Only ROW_KEYS are compared. A runner adds `kind` or a gold state to its in-memory
    copy of a row, and that annotation must not read as a hand-edited answer.
    """
    def view(row):
        return {k: row.get(k) for k in ROW_KEYS}

    fresh = generate_items()
    if [view(r) for r in rows] == [view(r) for r in fresh]:
        return True, f"{len(rows)} rows equal generate_items() on {list(ROW_KEYS)}"
    if len(rows) != len(fresh):
        return False, f"{len(rows)} rows on disk vs {len(fresh)} generated"
    for got, want in zip(rows, fresh):
        diff = [k for k in ROW_KEYS if got.get(k) != want.get(k)]
        if diff:
            return False, f"row {got.get('id')} differs in {diff}: {got} vs {want}"
    return False, "rows differ in order only"


def limit_rows(rows, n):
    """First n items, round-robin over (lang, steps) so a limited run keeps every group."""
    if not n or n >= len(rows):
        return list(rows)
    groups = {}
    for row in rows:
        key = (row.get("lang"), row.get("steps"))
        groups.setdefault(key, []).append(row)
    order = [k for k in ([(lang, s) for lang in LANGS for s in STEP_COUNTS]) if k in groups]
    out, index = [], 0
    while len(out) < n:
        added = False
        for key in order:
            if len(out) >= n:
                break
            if index < len(groups[key]):
                out.append(groups[key][index])
                added = True
        if not added:
            break
        index += 1
    return out


