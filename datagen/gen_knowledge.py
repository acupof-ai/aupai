def main():
    N = int(sys.argv[1])
    bank = [(d, q, a, e) for d, q, a, e in CURATED]
    bank.extend(("数学",) + t for t in DEFS)
    for fc, tc, ratio, dom in CONV:
        bank.append(
            (
                "生活/单位",
                f"1 {fc}等于多少{tc}？",
                f"{ratio} {tc}",
                f"这是{dom}单位换算，进率为 10 的整数次幂（或 24、7、1024 等），1 {fc} = {ratio} {tc}。",
            )
        )
    rng.shuffle(bank)
    rows = []
    seen = set()
    for d, q, a, e in bank:
        if len(rows) >= N:
            break
        if q in seen:
            continue
        seen.add(q)
        rows.append({"instruction": q, "output": f"答案：{a}\n\n解析：{e}"})
    with open(sys.argv[2], "w", encoding="utf-8") as f:
        for r in rows:
            f.write(json.dumps(r, ensure_ascii=False) + "\n")
    print(f"wrote {len(rows)} knowledge items", file=sys.stderr)


if __name__ == "__main__":
    main()
