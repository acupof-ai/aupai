#!/usr/bin/env python3
"""The eval holdout, as a hash set every data path must exclude.

`python datagen/holdout.py` regenerates data/eval/holdout_hashes.txt from the eval
files; importers use `is_holdout(question)`.

Fail-closed: the hash file carries a fingerprint of the eval files that produced
it. is_holdout() RAISES if the file is missing, predates fingerprints, or is
stale (an eval file changed since regeneration). A guard that silently returns
False is indistinguishable from no guard at all -- the 2026-08-30 sft_all.pt
contamination (19/20 holdout questions packed because the hash set was empty)
is the reason this is loud, not silent.

# restartable: main() accumulates one hash set and writes HASH_PATH once, which the
# restartability check flags -- correctly, as a shape. It is cheap here and the reason is
# measurable rather than asserted: the whole registry is 13 files and ~31,000 rows of sha1 over
# short strings, a few seconds, and the output is a single derived file that is regenerated by
# re-running the command with no state to resume. A partial write is also impossible to
# mistake for a good one: the file leads with `# fp:<fingerprint>` and load() RAISES on a
# fingerprint mismatch, so an interrupted run leaves a file the next reader refuses rather than
# a short hash set it silently trusts.
"""

